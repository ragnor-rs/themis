import org.jsoup.Jsoup
import org.jsoup.nodes.Document
import org.jsoup.nodes.Element
import java.net.URI
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import java.time.Duration

/**
 * Fetches regulation texts from the EU Publications Office and parses them into clauses.
 *
 * The text is requested from the Cellar repository rather than the eur-lex.europa.eu web front end: the
 * latter sits behind a JavaScript bot challenge that a plain HTTP client cannot pass, whereas Cellar
 * serves the same document over content negotiation with no challenge. The documents it returns are
 * byte-for-byte equivalent in structure to the ones this project previously kept checked in.
 *
 * The XHTML is generated by the Publications Office converter and is far more regular than ordinary web
 * markup. Two regions matter:
 *
 *  - `pbl_1`, the preamble, holding the numbered recitals as `rct_N`.
 *  - `enc_1`, the enacting terms, holding chapters (`cpt_X`), optional sections (`cpt_X.sct_Y`) and
 *    articles (`art_N`). An article's numbered paragraphs are wrapped in `<div id="NNN.MMM">`, where NNN
 *    is the article number and MMM the paragraph number.
 *
 * Sub-points — `(a)`, `(b)` — are laid out as two-column tables rather than lists, so the text extraction
 * has to fold a table's cells back into a line.
 */
private const val CELLAR_BASE = "http://publications.europa.eu/resource/celex/"

private val httpClient: HttpClient = HttpClient.newBuilder()
    .followRedirects(HttpClient.Redirect.NORMAL)
    .connectTimeout(Duration.ofSeconds(30))
    .build()

fun fetchRegulationXhtml(celexId: String): String {
    val request = HttpRequest.newBuilder(URI.create(CELLAR_BASE + celexId))
        // Both headers are required: without the language Cellar cannot pick a document expression,
        // and text/html is not an available content stream for these works.
        .header("Accept", "application/xhtml+xml")
        .header("Accept-Language", "eng")
        .timeout(Duration.ofMinutes(5))
        .GET()
        .build()

    val response = httpClient.send(request, HttpResponse.BodyHandlers.ofString())
    if (response.statusCode() != 200) {
        error(
            "Could not download CELEX $celexId from the EU Publications Office: " +
                "HTTP ${response.statusCode()}. ${response.body().take(300)}"
        )
    }
    return response.body()
}

private val CHAPTER_ID = Regex("^cpt_[^.]+$")
private val SECTION_ID = Regex("^cpt_[^.]+\\.sct_[^.]+$")
private val ARTICLE_ID = Regex("^art_[^.]+$")
private val RECITAL_ID = Regex("^rct_\\d+$")
private val CLAUSE_ID = Regex("^\\d+\\.\\d+$")
private val WHITESPACE = Regex("\\s+")
private const val NON_BREAKING_SPACE = '\u00a0'

/**
 * Recitals are not inside a chapter, so they are filed under a chapter number of their own to keep every
 * clause carrying the full set of metadata fields the bot reads.
 */
private const val RECITAL_CHAPTER_NUMBER = "0"

/** Articles that sit directly under a chapter still need a section number; the regulations start at 1. */
private const val DEFAULT_SECTION_NUMBER = "1"

/** Parses a regulation into one [Clause] per recital and per numbered article paragraph. */
fun parseClauses(xhtml: String): List<Clause> {
    val document = Jsoup.parse(xhtml)
    return parseRecitals(document) + parseArticles(document)
}

/**
 * The preamble's numbered recitals.
 *
 * They carry no obligations of their own but state what each article is for, which is what makes a
 * retrieved article intelligible to the model.
 */
private fun parseRecitals(document: Document): List<Clause> {
    val preamble = document.getElementById("pbl_1") ?: return emptyList()

    return preamble.select("div.eli-subdivision")
        .filter { RECITAL_ID.matches(it.id()) }
        .mapNotNull { recital ->
            val number = recital.id().removePrefix("rct_")

            // A recital is a two-column table: the marker '(N)' then the text. The number is taken from
            // the id rather than the marker, and the marker cell is dropped.
            val row = recital.children()
                .firstOrNull { it.tagName() == "table" }
                ?.select("tr")
                ?.firstOrNull()
            val description = if (row != null) {
                row.children()
                    .filter { it.tagName() == "td" }
                    .drop(1)
                    .joinToString("\n") { it.contentText() }
                    .trim()
            } else {
                recital.contentText()
            }

            description.takeIf { it.isNotEmpty() }?.let {
                Clause(
                    chapterNumber = RECITAL_CHAPTER_NUMBER,
                    chapterTitle = "",
                    sectionNumber = DEFAULT_SECTION_NUMBER,
                    sectionTitle = "",
                    articleNumber = number,
                    articleTitle = "Recital ($number)",
                    clauseNumber = "1",
                    description = it,
                )
            }
        }
}

/** The enacting terms: every numbered paragraph of every article, with its chapter and section context. */
private fun parseArticles(document: Document): List<Clause> {
    val enactingTerms = document.getElementById("enc_1") ?: document

    val articleElements = enactingTerms.select("div.eli-subdivision").filter { ARTICLE_ID.matches(it.id()) }

    return articleElements.flatMap { articleElement ->
        val articleNumber = articleElement.id().removePrefix("art_")

        // Annex subdivisions and the signature block share the markup but are not numbered articles.
        if (articleNumber.isEmpty() || !articleNumber.all { it.isDigit() }) {
            return@flatMap emptyList()
        }

        val chapterElement = articleElement.parents().firstOrNull { CHAPTER_ID.matches(it.id()) }
        val sectionElement = articleElement.parents().firstOrNull { SECTION_ID.matches(it.id()) }

        val context = ClauseContext(
            chapterNumber = chapterElement?.id()?.removePrefix("cpt_").orEmpty(),
            chapterTitle = chapterElement?.titleText().orEmpty(),
            sectionNumber = sectionElement?.id()?.substringAfter(".sct_") ?: DEFAULT_SECTION_NUMBER,
            sectionTitle = sectionElement?.titleText().orEmpty(),
            articleNumber = articleNumber,
            articleTitle = articleElement.titleText().orEmpty(),
        )

        val clauseElements = articleElement.select("div").filter { CLAUSE_ID.matches(it.id()) }
        if (clauseElements.isNotEmpty()) {
            clauseElements.mapNotNull { clauseElement ->
                val clauseNumber = clauseElement.id().substringAfter('.').trimStart('0').ifEmpty { "1" }
                clauseElement.contentText()
                    .stripLeadingClauseNumber(clauseNumber)
                    .takeIf { it.isNotEmpty() }
                    ?.let { context.toClause(clauseNumber, it) }
            }
        } else {
            // Articles that are a single unnumbered paragraph, and the definitions articles. The heading
            // and title are skipped for free here: neither is an `oj-normal` paragraph.
            listOfNotNull(
                articleElement.contentText()
                    .takeIf { it.isNotEmpty() }
                    ?.let { context.toClause("1", it) }
            )
        }
    }
}

private data class ClauseContext(
    val chapterNumber: String,
    val chapterTitle: String,
    val sectionNumber: String,
    val sectionTitle: String,
    val articleNumber: String,
    val articleTitle: String,
) {
    fun toClause(clauseNumber: String, description: String) = Clause(
        chapterNumber = chapterNumber,
        chapterTitle = chapterTitle,
        sectionNumber = sectionNumber,
        sectionTitle = sectionTitle,
        articleNumber = articleNumber,
        articleTitle = articleTitle,
        clauseNumber = clauseNumber,
        description = description,
    )
}

/** The paragraph number is already a metadata field, so it is not repeated at the head of the text. */
private fun String.stripLeadingClauseNumber(clauseNumber: String): String =
    removePrefix("$clauseNumber.").trimStart()

/**
 * Text of a clause, article body or table cell.
 *
 * Only direct children are read, so a nested article can never be absorbed into its parent. Paragraphs
 * are kept on separate lines, and each sub-point table is folded into one line of `marker text`.
 */
private fun Element.contentText(): String =
    children()
        .mapNotNull { child ->
            when {
                child.tagName() == "p" && child.hasClass("oj-normal") -> child.cleanText()
                child.tagName() == "table" -> child.subPointText()
                else -> null
            }
        }
        .filter { it.isNotEmpty() }
        .joinToString("\n")

/** Folds a sub-point table — a marker cell and a text cell — into a single line. */
private fun Element.subPointText(): String {
    val cells = select("td")
    if (cells.isEmpty()) {
        return ""
    }
    val marker = cells.first()!!.cleanText()
    val body = cells.drop(1).joinToString(" ") { it.cleanText() }
    return listOf(marker, body).filter { it.isNotEmpty() }.joinToString(" ")
}

/** Titles live in an `eli-title` child; a direct child only, so a section title is not read as its chapter's. */
private fun Element.titleText(): String? =
    children().firstOrNull { it.hasClass("eli-title") }?.cleanText()

/** Collapses the non-breaking spaces and line wrapping the converter emits into single spaces. */
private fun Element.cleanText(): String =
    text().replace(NON_BREAKING_SPACE, ' ').replace(WHITESPACE, " ").trim()
